import { sha256Object } from "../core/integrity";
import { SessionContractSchema } from "./contract";
import { buildSessionReceipt, RECORDER_VERSION, type ContractInfo, type SessionReceipt } from "./receipt";
import { checkSignature, type ReceiptSignature, type SignatureCheck } from "./signing";

/**
 * A self-contained, portable record of one session: the receipt plus the full
 * event log it was computed from. Anyone can re-run `verify` on it without
 * access to the original machine.
 */
export type ReceiptBundle = {
  schemaVersion: "1.0";
  kind: "work-receipt-bundle";
  receipt: SessionReceipt;
  events: unknown[];
  /** SHA-256 over the canonical receipt and events. */
  bundleDigest: string;
  /** Ed25519 signature over bundleDigest by the generating user's key. */
  signature?: ReceiptSignature;
};

export type BundleVerification = {
  consistent: boolean;
  verdict: SessionReceipt["verdict"] | null;
  problems: string[];
  signature: SignatureCheck;
  /** Set when the receipt was computed by a different recorder version. */
  versionMismatch?: string;
};

export function createBundle(receipt: SessionReceipt, events: unknown[]): ReceiptBundle {
  return {
    schemaVersion: "1.0",
    kind: "work-receipt-bundle",
    receipt,
    events,
    bundleDigest: sha256Object({ receipt, events }),
  };
}

/**
 * Recompute the receipt from the bundled events and the facts it recorded
 * (check results, working-tree changes, file digests) and compare. This proves
 * internal consistency: the verdict follows from the evidence and nothing was
 * edited after generation. It does not prove who produced the bundle or that
 * the recorded check results and git observations were truthful.
 */
export function verifyBundle(input: unknown): BundleVerification {
  const problems: string[] = [];
  const bundle = input as Partial<ReceiptBundle> | null;
  if (!bundle || bundle.kind !== "work-receipt-bundle" || !bundle.receipt || !Array.isArray(bundle.events)) {
    return { consistent: false, verdict: null, problems: ["Not a work receipt bundle."], signature: { status: "unsigned" } };
  }
  const { receipt, events } = bundle as ReceiptBundle;

  // Receipts are recomputed with this version's rules, so a receipt from another
  // version cannot be judged here. That is not evidence of tampering.
  if (receipt.recorderVersion !== RECORDER_VERSION) {
    const found = receipt.recorderVersion ?? "an earlier version";
    return {
      consistent: false,
      verdict: null,
      problems: ["Generated by recorder " + found + "; this verifier is " + RECORDER_VERSION + ". Verify with the matching version or regenerate the receipt."],
      signature: checkSignature(bundle.bundleDigest ?? "", bundle.signature),
      versionMismatch: found,
    };
  }

  if (sha256Object({ receipt, events }) !== bundle.bundleDigest) {
    problems.push("Bundle digest does not match its contents; the receipt or events were edited.");
  }

  let contract: ContractInfo;
  if (receipt.contract?.status === "loaded") {
    const parsed = SessionContractSchema.safeParse(receipt.contract.terms);
    if (!parsed.success) return { consistent: false, verdict: null, problems: [...problems, "Embedded contract is invalid."], signature: { status: "unsigned" } };
    if (sha256Object(parsed.data) !== receipt.contract.digest) problems.push("Embedded contract does not match its digest.");
    contract = { status: "loaded", contract: parsed.data };
  } else {
    contract = receipt.contract?.status === "invalid"
      ? { status: "invalid", message: "Contract was invalid when the receipt was generated." }
      : { status: "absent" };
  }

  const { outOfScope: _o, notFromFileTools: _n, ignored: _i, ...gitChanges } = receipt.workingTree;
  const recordedHashes = new Map(receipt.filesChanged.map((file) => [file.path, file.sha256]));
  const recomputed = buildSessionReceipt({
    sessionId: receipt.sessionId,
    events,
    contract,
    checks: receipt.checks,
    gitChanges,
    hashFile: (path) => recordedHashes.get(path) ?? null,
    now: new Date(receipt.generatedAt),
  });

  if (sha256Object(recomputed) !== sha256Object(receipt)) {
    for (const key of Object.keys(recomputed) as (keyof SessionReceipt)[]) {
      if (sha256Object(recomputed[key] ?? null) !== sha256Object(receipt[key] ?? null)) {
        problems.push("Field '" + key + "' does not follow from the bundled evidence.");
      }
    }
  }

  const signature = checkSignature(bundle.bundleDigest ?? "", bundle.signature);
  if (signature.status === "invalid") problems.push("Signature: " + signature.reason);

  return { consistent: problems.length === 0, verdict: recomputed.verdict, problems, signature };
}
