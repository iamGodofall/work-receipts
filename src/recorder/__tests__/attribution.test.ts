import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  agentDigests, ATTRIBUTION_SIDECAR, attribute, describeAttribution, digestListHash, lineDigest, lineDigests, loadOrCreateAttributionKey,
  MAX_DIGESTS_PER_WRITE, meaningfulLine, sessionAttributionKey, writtenText,
} from "../attribution";
import { addedLines } from "../git";
import { handleHook } from "../hook";
import { readEvents, sessionDir } from "../store";

const key = Buffer.alloc(32, 7);

describe("line normalisation and digests", () => {
  it("ignores indentation and line endings, and skips lines too generic to attribute", () => {
    expect(meaningfulLine("    return total;\r")).toBe("return total;");
    for (const generic of ["", "   ", "}", "});", "  ]", "/**", "ab"]) expect(meaningfulLine(generic)).toBeNull();
    expect(lineDigests(key, "  const a = 1;\n}\nconst a = 1;\r\n")).toEqual([lineDigest(key, "const a = 1;")]);
  });

  it("uses the key, so digests cannot be tested without it", () => {
    expect(lineDigest(key, "const a = 1;")).not.toBe(lineDigest(Buffer.alloc(32, 8), "const a = 1;"));
    expect(lineDigest(key, "const a = 1;")).toMatch(/^[0-9a-f]{16}$/);
  });

  it("caps digests per write", () => {
    const text = Array.from({ length: MAX_DIGESTS_PER_WRITE + 50 }, (_, index) => "line number " + index).join("\n");
    expect(lineDigests(key, text)).toHaveLength(MAX_DIGESTS_PER_WRITE);
  });

  it("reads the written text from each file tool's documented input", () => {
    expect(writtenText("Write", { content: "a" })).toBe("a");
    expect(writtenText("Edit", { old_string: "x", new_string: "b" })).toBe("b");
    expect(writtenText("MultiEdit", { edits: [{ new_string: "c" }, { new_string: "d" }, null] })).toBe("c\nd\n");
    expect(writtenText("NotebookEdit", { new_source: "e" })).toBe("e");
    expect(writtenText("Bash", { command: "echo" })).toBeNull();
  });
});

describe("attribution counts", () => {
  it("splits added lines into agent-written and other, per file", () => {
    const agent = new Set(lineDigests(key, "export function add(a, b) {\n  return a + b;\n}"));
    const result = attribute(new Map([
      ["src/add.ts", ["export function add(a, b) {", "    return a + b;", "}", ""]],
      ["src/gen.ts", ["// generated by tool v1", "export const version = 1;"]],
      ["src/empty.ts", ["}", ""]],
    ]), agent, key);
    expect(result).toEqual({
      available: true, agentLines: 2, otherLines: 2, filesTruncated: false,
      files: [{ path: "src/add.ts", agentLines: 2, otherLines: 0 }, { path: "src/gen.ts", agentLines: 0, otherLines: 2 }],
    });
    expect(describeAttribution(result)).toMatch(/^50% of added lines \(2 of 4\)/);
  });

  it("accepts sidecar digests only when a completed, chained event committed to that exact list", () => {
    const good = ["0123456789abcdef", "1111111111111111"];
    const sidecar = [
      JSON.stringify({ digests: good }),
      JSON.stringify({ digests: ["fedcba9876543210"] }), // not committed by any event: injected
      JSON.stringify({ digests: ["0123456789abcdef", "bad"] }),
      "not json",
    ].join("\n");
    const events = [
      { eventType: "tool.completed", payload: { lineDigestsHash: digestListHash(good) } },
      { eventType: "tool.requested", payload: { lineDigestsHash: digestListHash(["fedcba9876543210"]) } },
      null,
    ];
    expect([...agentDigests(sidecar, events)].sort()).toEqual(good);
  });

  it("derives a different key per session, so digests never link sessions or repositories", () => {
    const master = Buffer.alloc(32, 1);
    expect(sessionAttributionKey(master, "a").equals(sessionAttributionKey(master, "a"))).toBe(true);
    expect(lineDigest(sessionAttributionKey(master, "a"), "same line here")).not.toBe(lineDigest(sessionAttributionKey(master, "b"), "same line here"));
  });
});

describe("attribution end to end", () => {
  let repo = "";
  let home = "";
  const git = (...args: string[]) => {
    const result = spawnSync("git", args, { cwd: repo, encoding: "utf8" });
    if (result.status !== 0) throw new Error(result.stderr);
    return result.stdout.trim();
  };

  beforeEach(() => {
    repo = mkdtempSync(join(tmpdir(), "receipts-attr-"));
    home = mkdtempSync(join(tmpdir(), "receipts-home-"));
    git("init", "-q");
    git("config", "user.email", "test@example.invalid");
    git("config", "user.name", "Test");
    git("config", "core.autocrlf", "false");
    mkdirSync(join(repo, "src"));
    writeFileSync(join(repo, "src", "a.ts"), "export const a = 1;\n");
    git("add", ".");
    git("commit", "-q", "-m", "init");
  });

  afterEach(() => {
    rmSync(repo, { recursive: true, force: true });
    rmSync(home, { recursive: true, force: true });
  });

  it("records keyed digests on file-tool writes and attributes only the agent's lines", () => {
    const env = { CLAUDE_PROJECT_DIR: repo, WORK_RECEIPTS_HOME: home };
    const content = "export const a = 1;\nexport function double(value: number) {\n  return value * 2;\n}\n";
    handleHook("post", { session_id: "s1", tool_name: "Write", tool_input: { file_path: join(repo, "src", "a.ts"), content }, tool_use_id: "t1" }, env);
    writeFileSync(join(repo, "src", "a.ts"), content + "export const fromShell = 'formatter added this';\n");

    const dir = sessionDir(repo, "s1");
    const events = readEvents(dir);
    const completed = events.find((event) => (event as { eventType: string }).eventType === "tool.completed") as { payload: Record<string, unknown> };
    expect(completed.payload.lineDigestCount).toBe(3);
    // The chained log, which is embedded in shareable receipts, holds neither code nor line digests.
    const log = readFileSync(join(dir, "events.jsonl"), "utf8");
    expect(log).not.toMatch(/double|value \* 2/);
    expect(completed.payload).not.toHaveProperty("lineDigests");
    const sidecar = readFileSync(join(dir, ATTRIBUTION_SIDECAR), "utf8");
    for (const digest of JSON.parse(sidecar.trim()).digests as string[]) expect(log).not.toContain(digest);

    const added = addedLines(repo, git("rev-parse", "HEAD"), ["src/a.ts"]);
    expect(added.get("src/a.ts")).toEqual(["export function double(value: number) {", "  return value * 2;", "}", "export const fromShell = 'formatter added this';"]);
    const key = sessionAttributionKey(loadOrCreateAttributionKey(env), "s1");
    expect(attribute(added, agentDigests(sidecar, events), key)).toMatchObject({ available: true, agentLines: 2, otherLines: 1 });

    // Appending forged digests to the sidecar adds no authorship.
    const forged = JSON.stringify({ digests: lineDigests(key, "export const fromShell = 'formatter added this';") });
    expect(attribute(added, agentDigests(sidecar + forged + "\n", events), key)).toMatchObject({ agentLines: 2, otherLines: 1 });
  });

  it("treats new files as wholly added and skips deleted and binary files", () => {
    writeFileSync(join(repo, "src", "new.ts"), "export const created = true;\n");
    writeFileSync(join(repo, "src", "blob.bin"), Buffer.from([0, 1, 2, 3]));
    rmSync(join(repo, "src", "a.ts"));
    const added = addedLines(repo, git("rev-parse", "HEAD"), ["src/new.ts", "src/blob.bin", "src/a.ts"]);
    expect([...added.keys()]).toEqual(["src/new.ts"]);
    // A base commit that is not a full commit id never reaches git.
    expect(addedLines(repo, "--output=x", ["src/new.ts"]).size).toBe(0);
  });

  it("keeps the attribution key with the signing key and reuses it", () => {
    const env = { WORK_RECEIPTS_HOME: home };
    const first = loadOrCreateAttributionKey(env);
    expect(loadOrCreateAttributionKey(env).equals(first)).toBe(true);
    expect(readFileSync(join(home, "attribution.key"), "utf8").trim()).toBe(first.toString("hex"));
    writeFileSync(join(home, "attribution.key"), "garbage");
    expect(() => loadOrCreateAttributionKey(env)).toThrow(/malformed/);
  });
});
